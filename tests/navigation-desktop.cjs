const assert = require('node:assert/strict');
const { mkdir, writeFile } = require('node:fs/promises');

module.exports = async function verifyNavigation({ window, evaluate, click, fill, until, reopen, directory }) {
  await until(() => evaluate(`!!document.querySelector('nav[aria-label="项目导航"]')`));
  if (reopen) {
    await until(async () => (await evaluate('window.workbench.snapshot()')).navigation.width === 312);
    assert.equal(await evaluate(`document.querySelector('nav[aria-label="项目导航"]').getBoundingClientRect().width`), 0);
    await click('展开项目导航');
    await until(() => evaluate(`document.querySelector('nav[aria-label="项目导航"]').getBoundingClientRect().width === 312`));
    return;
  }
  const toggle = await evaluate(`(() => { const b = document.querySelector('button[aria-label="折叠项目导航"]').getBoundingClientRect(); return { x: b.x, y: b.y }; })()`);
  await click('折叠项目导航');
  await until(() => evaluate(`document.querySelector('nav[aria-label="项目导航"]').getBoundingClientRect().width === 0`));
  assert.equal(await evaluate(`document.querySelector('main').getBoundingClientRect().left`), 0, 'hidden navigation leaves no narrow rail');
  assert.deepEqual(await evaluate(`(() => { const b = document.querySelector('button[aria-label="展开项目导航"]').getBoundingClientRect(); return { x: b.x, y: b.y }; })()`), toggle);
  await click('展开项目导航');
  await until(() => evaluate(`document.querySelector('nav[aria-label="项目导航"]').getBoundingClientRect().width === 212`));
  window.focus(); window.webContents.focus();
  const edge = await evaluate(`(() => { const b = document.querySelector('[aria-label="调整项目导航宽度"]').getBoundingClientRect(); return { x: Math.round(b.x + b.width / 2), y: Math.round(b.y + b.height / 2) }; })()`);
  window.webContents.sendInputEvent({ type: 'mouseDown', ...edge, button: 'left', clickCount: 1 });
  window.webContents.sendInputEvent({ type: 'mouseMove', x: edge.x + 50, y: edge.y, modifiers: ['leftButtonDown'] });
  await until(() => evaluate(`document.querySelector('nav[aria-label="项目导航"]').getBoundingClientRect().width === 262`));
  assert.equal((await evaluate('window.workbench.snapshot()')).navigation.width, 212, 'resize remains transient until release');
  window.webContents.sendInputEvent({ type: 'mouseMove', x: edge.x + 100, y: edge.y, modifiers: ['leftButtonDown'] });
  window.webContents.sendInputEvent({ type: 'mouseUp', x: edge.x + 100, y: edge.y, button: 'left', clickCount: 1 });
  await until(async () => (await evaluate('window.workbench.snapshot()')).navigation.width === 312);
  assert.deepEqual(await evaluate(`(() => { const b = document.querySelector('button[aria-label="折叠项目导航"]').getBoundingClientRect(); return { x: b.x, y: b.y }; })()`), toggle);
  await fill('project-name', 'Preserved setup draft');
  await click('增加Codex');
  await click('全局设置');
  assert.equal(await evaluate(`document.querySelector('nav[aria-label="项目导航"]').getBoundingClientRect().width`), 312, 'settings preserve the navigation width');
  assert.equal(await evaluate(`document.querySelector('nav[aria-label="项目导航"] button[aria-label="全局设置"]').getAttribute('aria-current')`), 'page');
  assert.equal(await evaluate(`document.querySelector('.add-project').getAttribute('aria-current')`), null);
  await click('全局设置');
  await until(() => evaluate(`!document.querySelector('.settings-page')`));
  assert.equal(await evaluate(`document.getElementById('project-name').value`), 'Preserved setup draft');
  assert.match(await evaluate('document.body.innerText'), /已分配 1 \/ 3/);
  await click('取消');
  await click('全局设置');
  await click('‹ 返回');
  await until(() => evaluate(`!document.querySelector('.settings-page')`));
  assert.match(await evaluate('document.body.innerText'), /让你的 Agent 在同一个工作台中并行工作/);
  await click('全局设置');
  await click('添加项目');
  await until(() => evaluate(`!document.querySelector('.settings-page')`));
  assert.equal(await evaluate(`document.getElementById('project-name').value`), 'Preserved setup draft');
  const key = (keyCode, modifiers = ['meta']) => {
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode, modifiers });
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode, modifiers });
  };
  await evaluate(`window.navigationOutput = []; window.workbench.subscribe(event => { if (event.kind === 'output') window.navigationOutput.push(event); }); void 0`);
  const createProject = async (name, total = 1) => {
    const path = `${directory}/${name}`;
    await mkdir(path);
    return evaluate(`window.workbench.createProject(${JSON.stringify({ name, directory: path, total, counts: { codex: total, claude: 0, pi: 0 } })})`);
  };
  const { project: first } = await createProject('Navigation first', 2);
  const { project: second } = await createProject('Navigation second');
  await click(first.name);
  await until(() => evaluate(`document.activeElement?.closest('[data-panel-id]')?.dataset.panelId === ${JSON.stringify(first.panels[0].id)}`));
  key('Return');
  await until(() => evaluate(`!!document.querySelector('button[aria-label="还原面板"]')`));
  const before = await evaluate('window.workbench.snapshot()');
  key(',');
  await until(() => evaluate(`!!document.querySelector('.settings-page')`));
  for (const [code, modifiers] of [['N', ['meta']], [']', ['meta', 'shift']], [']', ['meta']], ['Return', ['meta']]]) key(code, modifiers);
  await evaluate('new Promise(resolve => requestAnimationFrame(resolve))');
  assert.equal((await evaluate('window.workbench.snapshot()')).activeProjectId, first.id);
  assert.equal(await evaluate(`!!document.querySelector('dialog[open]')`), false);
  assert.equal(await evaluate(`document.querySelectorAll('.project-link[aria-current="page"]').length`), 0);
  key(',');
  await until(() => evaluate(`!document.querySelector('.settings-page')`));
  await until(() => evaluate(`document.activeElement?.closest('[data-panel-id]')?.dataset.panelId === ${JSON.stringify(first.panels[0].id)}`));
  assert.equal(await evaluate(`!!document.querySelector('button[aria-label="还原面板"]')`), true);
  assert.deepEqual((await evaluate('window.workbench.snapshot()')).runs, before.runs);
  await until(() => evaluate(`window.navigationOutput.some(event => event.runId === ${JSON.stringify(before.runs.find(run => run.panelId === first.panels[0].id).id)} && event.data.includes('READY:'))`));
  window.webContents.sendInputEvent({ type: 'char', keyCode: 'u' });
  await until(() => evaluate(`window.navigationOutput.some(event => event.data.includes('INPUT:u'))`));
  assert.deepEqual(await evaluate(`[...new Set(window.navigationOutput.filter(event => event.data.includes('INPUT:u')).map(event => event.runId))]`), [before.runs.find(run => run.panelId === first.panels[0].id).id]);
  await click('添加 Agent');
  key(',');
  await evaluate('new Promise(resolve => requestAnimationFrame(resolve))');
  assert.equal(await evaluate(`!!document.querySelector('.settings-page')`), false, 'dialogs suppress settings shortcut');
  await click('关闭添加 Agent');
  await click('全局设置');
  await click('快捷键');
  await evaluate(`document.getElementById('shortcut-nextPanel').focus()`);
  key(',');
  await evaluate('new Promise(resolve => requestAnimationFrame(resolve))');
  assert.equal(await evaluate(`!!document.querySelector('.settings-page')`), true, 'recorder consumes the settings shortcut');
  assert.equal((await evaluate('window.workbench.snapshot()')).settings.shortcuts.nextPanel, before.settings.shortcuts.nextPanel);
  key('Escape', []);
  assert.equal(await evaluate(`!!document.querySelector('.settings-page')`), true, 'Escape does not leave settings');
  await click(first.name);
  await until(() => evaluate(`!document.querySelector('.settings-page')`));
  assert.equal(await evaluate(`!!document.querySelector('button[aria-label="还原面板"]')`), true);
  await click('全局设置');
  await click(second.name);
  await until(async () => (await evaluate('window.workbench.snapshot()')).activeProjectId === second.id);
  assert.equal(await evaluate(`!!document.querySelector('.settings-page')`), false);
  assert.equal((await evaluate('window.workbench.snapshot()')).navigation.width, 312);
  for (let index = 0; index < 12; index++) {
    const { project } = await createProject(`Empty navigation ${index}`);
    await evaluate(`window.workbench.closePanel(${JSON.stringify(project.id)}, ${JSON.stringify(project.panels[0].id)})`);
  }
  window.setSize(760, 580);
  await until(() => evaluate(`innerWidth === 760`));
  const footer = await evaluate(`(() => { const b = document.querySelector('.settings-entry').getBoundingClientRect(); return { x: b.x, y: b.y }; })()`);
  await evaluate(`document.querySelector('.navigation-projects').scrollTop = 10000`);
  assert.ok(await evaluate(`document.querySelector('.navigation-projects').scrollTop > 0`));
  assert.deepEqual(await evaluate(`(() => { const b = document.querySelector('.settings-entry').getBoundingClientRect(); return { x: b.x, y: b.y }; })()`), footer);
  await click('全局设置');
  assert.equal(await evaluate(`(() => { const b = document.querySelector('.settings-back').getBoundingClientRect(); return b.x >= 312 && b.right <= innerWidth && b.bottom < innerHeight; })()`), true);
  await evaluate(`document.getElementById('command-pi').scrollIntoView({ block: 'end' })`);
  assert.equal(await evaluate(`document.querySelector('.settings-back').getBoundingClientRect().top >= 44`), true, 'return remains available after scrolling settings');
  await click('折叠项目导航');
  assert.equal(await evaluate(`!!document.querySelector('.settings-page')`), true);
  await click('‹ 返回');
  await until(() => evaluate(`!document.querySelector('.settings-page')`));
  key(',');
  await until(() => evaluate(`!!document.querySelector('.settings-page')`));
  assert.equal(await evaluate(`document.querySelector('nav[aria-label="项目导航"]').getBoundingClientRect().width`), 0);
  key(',');
  await until(() => evaluate(`!document.querySelector('.settings-page')`));
  await click('展开项目导航');
  await click(first.name);
  await require('./notices-desktop.cjs')({ window, evaluate, click, fill, until, project: first, directory });
  await until(() => evaluate(`!!document.querySelector('.settings-page') && !document.querySelector('.notice')`));
  await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
  await mkdir('work/issue-46', { recursive: true });
  await writeFile('work/issue-46/navigation-settings.png', (await window.webContents.capturePage()).toPNG());
  await click('‹ 返回');
  await click('折叠项目导航');
  await until(async () => !(await evaluate('window.workbench.snapshot()')).navigation.visible);
};
