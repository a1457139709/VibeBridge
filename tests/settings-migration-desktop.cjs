const assert = require('node:assert/strict');
module.exports = async function verifySettingsMigration({ window, evaluate, click, fill, until }) {
  await until(() => evaluate(`!!document.getElementById('project-name')`));
  const original = (await evaluate('window.workbench.snapshot()')).settings;
  assert.deepEqual((await evaluate('window.workbench.snapshot()')).errors, []);
  await click('全局设置'); await click('快捷键');
  assert.equal(await evaluate(`document.getElementById('shortcut-closePanel').title`), 'Command+Shift+W');
  assert.equal(await evaluate(`document.querySelectorAll('.shortcut-row input[aria-invalid="true"]').length`), 2, 'migration conflict remains visible without blocking startup');
  await click('恢复默认设置');
  assert.equal(await evaluate(`document.querySelectorAll('.shortcut-row input[aria-invalid="true"]').length`), 0);
  await click('放弃更改');
  assert.equal(await evaluate(`document.querySelectorAll('.shortcut-row input[aria-invalid="true"]').length`), 2, 'Discard restores the real conflict from migrated saved values');
  await click('外观'); await evaluate(`document.querySelector('input[value="dark"]').click()`);
  await click('保存');
  await until(() => evaluate(`document.querySelector('[aria-label="设置分类"] [aria-current="page"]').textContent === '快捷键'`));
  assert.match(await evaluate(`document.querySelector('.settings-status').textContent`), /存在按键冲突，未保存/);
  assert.deepEqual((await evaluate('window.workbench.snapshot()')).settings, original);
  await evaluate(`document.getElementById('shortcut-nextPanel').focus()`);
  window.focus(); window.webContents.focus();
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'K', modifiers: ['meta'] });
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'K', modifiers: ['meta'] });
  await until(() => evaluate(`document.getElementById('shortcut-nextPanel').title === 'Command+K'`));
  await click('‹ 返回'); await click('保存并返回');
  await until(() => evaluate(`!document.querySelector('.settings-page')`));
  const saved = (await evaluate('window.workbench.snapshot()')).settings;
  assert.equal(saved.theme, 'dark'); assert.equal(saved.shortcuts.nextPanel, 'Command+K');
  assert.deepEqual(saved.agents, original.agents); assert.equal(saved.defaultLayout, original.defaultLayout);
  await click('全局设置'); await fill('command-codex', '/unsaved-quit-draft');
  assert.equal((await evaluate('window.workbench.snapshot()')).settings.agents.codex.command, original.agents.codex.command);
  return { settingsBeforeQuit: saved };
};
