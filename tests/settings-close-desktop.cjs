const assert = require('node:assert/strict');
module.exports = async function verifyCloseShortcut({ window, evaluate, click, until }) {
  const before = await evaluate('window.workbench.snapshot()');
  const project = before.projects.find(p => p.id === before.activeProjectId);
  const [first, selected, last] = project.panels;
  const key = (keyCode, modifiers = ['meta']) => {
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode, modifiers });
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode, modifiers });
  };
  await click('全局设置'); key('W', ['meta', 'shift']);
  await evaluate('new Promise(resolve => requestAnimationFrame(resolve))');
  assert.deepEqual((await evaluate('window.workbench.snapshot()')).projects, before.projects, 'close shortcut is suppressed in settings');
  await click('快捷键');
  assert.equal(await evaluate(`document.getElementById('shortcut-closePanel').title`), 'Command+Shift+W');
  await click('‹ 返回');
  await evaluate(`document.querySelector('[data-panel-id="${selected.id}"] .panel-header').click()`);
  await until(() => evaluate(`document.activeElement?.closest('[data-panel-id]')?.dataset.panelId === '${selected.id}'`));
  key('W', ['meta', 'shift']);
  await until(async () => !(await evaluate('window.workbench.snapshot()')).projects.find(p => p.id === project.id).panels.some(p => p.id === selected.id));
  const afterSplit = await evaluate('window.workbench.snapshot()');
  assert.deepEqual(afterSplit.runs, before.runs.filter(r => r.panelId !== selected.id));
  assert.throws(() => process.kill(before.runs.find(r => r.panelId === selected.id).pid, 0));
  assert.equal(await evaluate(`!!document.querySelector('dialog[open]')`), false);
  await evaluate(`document.querySelector('[data-panel-id="${last.id}"] button[aria-label="放大面板"]').click()`);
  await until(() => evaluate(`document.activeElement?.closest('[data-panel-id]')?.dataset.panelId === '${last.id}'`));
  key('W', ['meta', 'shift']);
  await until(async () => (await evaluate('window.workbench.snapshot()')).projects.find(p => p.id === project.id).panels.length === 1);
  assert.throws(() => process.kill(before.runs.find(r => r.panelId === last.id).pid, 0));
  assert.equal(await evaluate(`!!document.querySelector('button[aria-label="还原面板"]')`), false);
  await until(() => evaluate(`document.activeElement?.closest('[data-panel-id]')?.dataset.panelId === '${first.id}'`));
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('[data-panel-id="${first.id}"]')).visibility`), 'visible');
  key('W', ['meta', 'shift']);
  await until(async () => (await evaluate('window.workbench.snapshot()')).projects.find(p => p.id === project.id).panels.length === 0);
  assert.equal((await evaluate('window.workbench.snapshot()')).activeProjectId, project.id);
  assert.match(await evaluate('document.body.innerText'), /这个项目还没有 Agent 面板/);
  assert.throws(() => process.kill(before.runs.find(r => r.panelId === first.id).pid, 0));
};
