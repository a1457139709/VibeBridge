const assert = require('node:assert/strict');

module.exports = {
  async run({ window, evaluate, click, fill, until, directory }) {
    await until(() => evaluate(`!!document.getElementById('project-name')`));
    const { project } = await evaluate(`window.workbench.createProject(${JSON.stringify({ name: 'Settings draft project', directory, total: 3, counts: { codex: 3, claude: 0, pi: 0 } })})`);
    await click(project.name);
    window.focus(); window.webContents.focus();
    await until(() => evaluate(`document.activeElement?.classList.contains('xterm-helper-textarea')`));
    const key = (keyCode, modifiers = ['meta']) => {
      window.webContents.sendInputEvent({ type: 'keyDown', keyCode, modifiers });
      window.webContents.sendInputEvent({ type: 'keyUp', keyCode, modifiers });
    };
    window.focus(); window.webContents.focus();
    const before = await evaluate('window.workbench.snapshot()');
    await click('全局设置');
    await click('快捷键');
    await evaluate(`document.getElementById('shortcut-nextPanel').focus()`);
    key('K');
    await until(() => evaluate(`document.getElementById('shortcut-nextPanel').title === 'Command+K'`));
    assert.equal((await evaluate('window.workbench.snapshot()')).settings.shortcuts.nextPanel, before.settings.shortcuts.nextPanel, 'recording edits only a draft');
    await click('Agent');
    await click('快捷键');
    assert.equal(await evaluate(`document.getElementById('shortcut-nextPanel').title`), 'Command+K');
    await click('保存');
    await until(async () => (await evaluate('window.workbench.snapshot()')).settings.shortcuts.nextPanel === 'Command+K');
    await click('Agent');
    await fill('command-codex', '');
    await click('外观');
    await evaluate(`document.querySelector('input[value="dark"]').click()`);
    await click('快捷键');
    await evaluate(`document.getElementById('shortcut-previousPanel').focus()`); key('L');
    await until(() => evaluate(`document.getElementById('shortcut-previousPanel').title === 'Command+L'`));
    await click('保存');
    await until(async () => (await evaluate('window.workbench.snapshot()')).settings.shortcuts.previousPanel === 'Command+L');
    const partial = (await evaluate('window.workbench.snapshot()')).settings;
    assert.equal(partial.theme, before.settings.theme);
    assert.equal(partial.agents.codex.command, before.settings.agents.codex.command);
    await click('外观');
    assert.equal(await evaluate(`document.querySelector('input[value="dark"]').checked`), true);
    await click('Agent');
    assert.equal(await evaluate(`document.getElementById('command-codex').value`), '');
    await click('保存');
    await until(() => evaluate(`document.getElementById('command-codex').getAttribute('aria-invalid') === 'true'`));
    assert.match(await evaluate(`document.querySelector('.settings-page').textContent`), /启动命令不能为空/);
    assert.match(await evaluate(`document.querySelector('.settings-page').textContent`), /存在需修正的设置，未保存/);
    await until(() => evaluate(`document.activeElement.id === 'command-codex'`));
    await click('‹ 返回');
    await until(() => evaluate(`!!document.querySelector('dialog[open]')`));
    const message = await evaluate(`document.querySelector('dialog').textContent`);
    assert.match(message, /Agent/); assert.match(message, /外观/); assert.doesNotMatch(message, /快捷键/);
    await click('取消');
    assert.ok(await evaluate(`!!document.querySelector('.settings-page')`));
    await click('‹ 返回'); await click('保存并返回');
    await until(() => evaluate(`document.activeElement.id === 'command-codex'`));
    assert.ok(await evaluate(`!!document.querySelector('.settings-page')`));
    await click('‹ 返回'); await click('不保存');
    await until(() => evaluate(`!document.querySelector('.settings-page')`));
    await require('./scenarios/settings-conflicts.cjs')({ window, evaluate, click, until });
    await require('./scenarios/settings-scroll.cjs')({ window, evaluate, click, until });
    await require('./scenarios/settings-categories.cjs')({ window, evaluate, click, fill, until, directory });
    assert.deepEqual((await evaluate('window.workbench.snapshot()')).runs, before.runs);
    await require('./scenarios/settings-leave.cjs')({ window, evaluate, click, fill, until, directory });
    await require('./scenarios/settings-close.cjs')({ window, evaluate, click, until });
    await require('./scenarios/settings-feedback.cjs')({ window, evaluate, click, fill, until, directory });
  },
};
